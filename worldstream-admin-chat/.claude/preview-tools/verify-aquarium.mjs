import assert from 'node:assert/strict';
import { chromium } from './node_modules/playwright/index.mjs';
const root = process.cwd();
const context = await chromium.launchPersistentContext(`${root}/.claude/preview-tools/profile`, { headless:true, viewport:{width:1920,height:1080} });
const page = context.pages()[0];
const errors=[];
page.on('pageerror', e=>errors.push(e.message));
await page.addInitScript(() => {
  window.renderedText=[];
  const fill=CanvasRenderingContext2D.prototype.fillText;
  const clear=CanvasRenderingContext2D.prototype.clearRect;
  CanvasRenderingContext2D.prototype.clearRect=function(...a) { if(this.canvas.id==='c') window.renderedText=[]; return clear.apply(this,a); };
  CanvasRenderingContext2D.prototype.fillText=function(t,...a) { if(this.canvas.id==='c') window.renderedText.push(String(t)); return fill.call(this,t,...a); };
});
const scene=await (await fetch('http://127.0.0.1:4401/scene?case=screens')).json();
assert.equal(scene.entities.filter(e=>e.screen).length,1);
let start=0;
await page.routeWebSocket('**/ws*',ws=>ws.send(JSON.stringify({t:'state',rev:1,serverTime:start,scene})));
const goto=async(time,text)=>{
  start=time;
  await page.goto('http://127.0.0.1:4401/?case=screens');
  await page.waitForFunction(t=>window.renderedText.includes(t),text);
};
await goto(0,'BOX TELEMETRY');
await page.screenshot({path:`${root}/.claude/preview-tools/aquarium-box.png`});
const tank=()=>page.evaluate(()=>Array.from(document.querySelector('canvas').getContext('2d').getImageData(1464,516,216,124).data));
const first=await tank();
await page.waitForTimeout(1000);
assert.notDeepEqual(await tank(),first);
await goto(24_000,'ROOM UPDATE');
await page.screenshot({path:`${root}/.claude/preview-tools/aquarium-flash.png`});
await page.waitForTimeout(400);
assert.ok(await page.evaluate(()=>window.renderedText.includes('POWER / CIRCUIT A')&&!window.renderedText.includes('ROOM UPDATE')));
await page.screenshot({path:`${root}/.claude/preview-tools/aquarium-room.png`});
await goto(31_000,'BOX TELEMETRY');
await page.emulateMedia({reducedMotion:'reduce'});
await goto(24_000,'POWER / CIRCUIT A');
assert.ok(await page.evaluate(()=>!window.renderedText.includes('ROOM UPDATE')));
assert.deepEqual(errors,[]);
console.log('PASS: one telemetry monitor, animated tank, pulse then room data, return to boxes, reduced-motion suppression, no browser errors');
await context.close();
